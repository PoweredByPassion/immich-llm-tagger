def t(key: str, lang: str = DEFAULT_LANG) -> str:
    """取词条。回退链：lang 非法 → zh；词条缺失 → 直接返回 key；
    词条存在但该语言为空串 → 退回 zh；zh 也缺 → 再退回 key。"""
    if lang not in SUPPORTED:
        lang = DEFAULT_LANG
    entry = _DICTIONARY.get(key)
    if entry is None:
        return key
    return entry.get(lang) or entry.get(DEFAULT_LANG) or key


def render_problems(problems, lang: str = DEFAULT_LANG) -> str:
    """把 store 层 `Problem`（i18n key + 位置参数）渲染成当前语言的单串。

    用 common.semi_sep 连接（zh「；」/ en「; 」）。无参数直接取词条，有参数按
    位置格式化——词条里 %s 数量 zh/en 一致由守门测试保证（test_web_i18n）。
    """
    sep = t("common.semi_sep", lang)
    parts: list[str] = []
    for p in problems:
        text = t(p.key, lang)
        parts.append(text % p.args if p.args else text)
    return sep.join(parts)


def lang_from_cookie(cookies: dict | None) -> str:
    raw = cookies.get("lang", "") if cookies else ""
    return raw if raw in SUPPORTED else DEFAULT_LANG


@pass_context
def _tr(context, key: str) -> str:
    return t(key, _lang(context))


@pass_context
def _lang(context) -> str:
    request = context.get("request")
    return lang_from_cookie(getattr(request, "cookies", None))


def install_template_globals(env: Environment) -> None:
    """挂到任意 Jinja 环境（app.py 的 templates.env 与测试的裸 env）。
    全局名 tr / lang —— 避开 usage.html 的循环变量 t。"""
    env.globals["tr"] = _tr
    env.globals["lang"] = _lang


def install(templates: Jinja2Templates) -> None:
    """Jinja2Templates 便捷入口。"""
    install_template_globals(templates.env)
